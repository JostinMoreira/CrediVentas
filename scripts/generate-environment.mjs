import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { loadEnvFile } from 'node:process';
if (existsSync('.env')) loadEnvFile('.env');
const required = name => {
  const value = process.env[name]?.trim();
  if (!value || /YOUR_|REEMPLAZAR/.test(value)) throw new Error('Falta configurar ' + name + ' en .env o en el entorno de compilación.');
  return value;
};
const supabaseUrl = required('SUPABASE_URL').replace(/\/$/, '');
const url = new URL(supabaseUrl);
if (url.protocol !== 'https:' && !(url.protocol === 'http:' && ['127.0.0.1', 'localhost'].includes(url.hostname))) throw new Error('SUPABASE_URL debe usar HTTPS (HTTP solo se permite en desarrollo local).');
if (url.username || url.password || url.search || url.hash || url.pathname !== '/') throw new Error('SUPABASE_URL debe ser el origen del proyecto, sin credenciales ni rutas.');
const supabaseKey = required('SUPABASE_PUBLISHABLE_KEY');
let publicKey = /^sb_publishable_[A-Za-z0-9_-]+$/.test(supabaseKey);
if (supabaseKey.startsWith('eyJ')) {
  try { publicKey = JSON.parse(Buffer.from(supabaseKey.split('.')[1], 'base64url').toString()).role === 'anon'; } catch { publicKey = false; }
}
if (!publicKey) throw new Error('Usa una clave publishable o anon. Nunca uses service_role ni sb_secret en el frontend.');
const whatsappPhone = required('WHATSAPP_PHONE').replace(/[ +()-]/g, '');
if (!/^[1-9][0-9]{7,14}$/.test(whatsappPhone)) throw new Error('WHATSAPP_PHONE debe incluir país y entre 8 y 15 dígitos.');
mkdirSync('src/environments', { recursive: true });
writeFileSync('src/environments/environment.generated.ts', '// Generated by scripts/generate-environment.mjs. Public browser configuration only.\nexport const environment = ' + JSON.stringify({ production: process.argv.includes('--production'), supabaseUrl, supabaseKey, whatsappPhone }, null, 2) + ' as const;\n');
console.log('Configuración pública generada.');
